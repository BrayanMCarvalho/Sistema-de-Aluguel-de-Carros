CREATE TABLE usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(255) NOT NULL UNIQUE, senha VARCHAR(255) NOT NULL,
 nome VARCHAR(255) NOT NULL, papel VARCHAR(20) NOT NULL CHECK (papel IN ('CLIENTE','EMPRESA','BANCO','ADMIN'))
);
CREATE TABLE clientes (
 id BIGINT PRIMARY KEY REFERENCES usuarios(id), nome VARCHAR(255) NOT NULL,
 rg VARCHAR(255) NOT NULL, cpf VARCHAR(255) NOT NULL UNIQUE,
 endereco VARCHAR(255) NOT NULL, profissao VARCHAR(255) NOT NULL
);
CREATE TABLE empregos (
 cliente_id BIGINT NOT NULL REFERENCES clientes(id), ordem INTEGER NOT NULL CHECK(ordem BETWEEN 0 AND 2),
 empregador VARCHAR(255), rendimento NUMERIC(12,2) CHECK(rendimento>=0), PRIMARY KEY(cliente_id,ordem)
);
CREATE TABLE automoveis (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 matricula VARCHAR(255) NOT NULL UNIQUE, ano INTEGER NOT NULL, marca VARCHAR(255), modelo VARCHAR(255),
 placa VARCHAR(255) UNIQUE, diaria NUMERIC(12,2) CHECK(diaria>0), proprietario_tipo VARCHAR(20), proprietario_nome VARCHAR(255)
);
CREATE TABLE pedidos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, versao BIGINT,
 cliente_id BIGINT NOT NULL REFERENCES clientes(id), automovel_id BIGINT NOT NULL REFERENCES automoveis(id),
 inicio DATE, fim DATE, status VARCHAR(30), total NUMERIC(12,2), observacoes VARCHAR(255),
 parecer VARCHAR(255), agente_id BIGINT REFERENCES usuarios(id), criado_em TIMESTAMP WITH TIME ZONE,
 CHECK(fim>inicio), CHECK(status IN ('EM_ANALISE','APROVADO','REPROVADO','CANCELADO','CONTRATADO'))
);
CREATE INDEX pedidos_cliente_idx ON pedidos(cliente_id);
CREATE TABLE contratos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 pedido_id BIGINT NOT NULL UNIQUE REFERENCES pedidos(id), cliente_id BIGINT REFERENCES clientes(id),
 proprietario_tipo VARCHAR(20), proprietario_nome VARCHAR(255), banco_id BIGINT REFERENCES usuarios(id),
 valor_credito NUMERIC(12,2), parcelas INTEGER, emitido_em TIMESTAMP WITH TIME ZONE,
 CHECK ((banco_id IS NULL AND valor_credito IS NULL AND parcelas IS NULL) OR
 (banco_id IS NOT NULL AND valor_credito>0 AND parcelas>0))
);
